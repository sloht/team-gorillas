"""Build a tournament agent.py that plays an evolved_policy genome.

    python build_agent.py                                   # evolution/champion.json -> submission_agent/
    python build_agent.py --champion path/champion.json --out some_folder

The output folder is a complete copy of the official bundle (taken from
potshove08_agent/, which holds the unchanged bundle files at commit c83ab6e)
with agent.py rewritten: the policy code between the POLICY START and POLICY
END markers in evolved_policy.py is copied in verbatim, followed by the
champion's genome and the three bundle functions. Everything is in that one
agent.py; it imports only the bundle's evaluator.py and game.py, like the
starter file.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEMPLATE_DIR = HERE / "potshove08_agent"
POLICY_FILE = HERE / "evolved_policy.py"
START, END = "# ===== YOUR CODE HERE =====", "# ===== END OF YOUR CODE ====="

AGENT_CODE = '''
# Generated by build_agent.py from evolved_policy.py: the strategy is the
# genome {name!r}. Do not edit by hand; change evolved_policy.py and rebuild.

{policy}

GENOME = Genome.from_dict({genome})

# Time safety valve. The judge gives 8 s of thinking per 1000-hand half; when
# it runs out the bot can only check or fold for the rest of the half. A full
# half normally uses 2-4 s, so this never triggers at normal speed. On a much
# slower machine it switches to fewer equity samples instead of running out.
SLOW_AFTER_SECONDS, SLOW_SAMPLES = 5.0, 6
VERY_SLOW_AFTER_SECONDS, VERY_SLOW_SAMPLES = 6.5, 2


def new_half(config: AgentConfig, memory: dict) -> None:
    """Called at the start of each half-match (1000 hands). `memory` starts empty."""
    memory["policy"] = EvolvedPolicy(GENOME, name=AGENT_NAME)  # fresh opponent model and rng
    memory["think_seconds"] = 0.0
    memory["hands_played"] = 0


def choose_action(obs: Observation, memory: dict) -> Action:
    """Called every time it is your turn. Returns one of obs.legal_actions."""
    start = time.perf_counter()
    used = memory["think_seconds"]
    samples = (None if used < SLOW_AFTER_SECONDS
               else SLOW_SAMPLES if used < VERY_SLOW_AFTER_SECONDS else VERY_SLOW_SAMPLES)
    action = memory["policy"].act(obs, samples)
    memory["think_seconds"] = used + time.perf_counter() - start
    # Belt and braces: never send an illegal action (each one costs an error).
    return action if action in obs.legal_actions else Action.CHECK_CALL


def on_hand_end(result: HandResult, memory: dict) -> None:
    """Called once for every finished hand: the policy's opponent model learns from it."""
    memory["policy"].on_hand_end(result)
    memory["hands_played"] += 1

'''


def policy_source() -> str:
    text = POLICY_FILE.read_text(encoding="utf-8")
    match = re.search(r"# ===== POLICY START.*?\n(.*?)# ===== POLICY END =====", text, re.S)
    if not match:
        raise SystemExit(f"No POLICY START/END markers in {POLICY_FILE}")
    return match.group(1).rstrip()


def build(champion: dict, out: Path, participant: str) -> Path:
    if out.resolve() != TEMPLATE_DIR.resolve():
        if out.exists():
            shutil.rmtree(out)
        shutil.copytree(TEMPLATE_DIR, out, ignore=shutil.ignore_patterns(
            "__pycache__", ".pytest_cache", "POTSHOVE08.md"))
    source = (TEMPLATE_DIR / "agent.py").read_text(encoding="utf-8")
    head, rest = source.split(START, 1)
    _, tail = rest.split(END, 1)
    head = re.sub(r'PARTICIPANT = ".*?"', f'PARTICIPANT = "{participant}"', head)
    head = re.sub(r'AGENT_NAME = ".*?"', f'AGENT_NAME = "{champion["id"]}"', head)
    body = AGENT_CODE.format(name=champion["id"], policy=policy_source(),
                             genome=json.dumps(champion["genome"], sort_keys=True))
    (out / "agent.py").write_text(head + START + "\n" + body + END + tail, encoding="utf-8")
    return out / "agent.py"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--champion", default="evolution/champion.json",
                        help="A champion.json written by champion_search.py.")
    parser.add_argument("--out", default="submission_agent")
    parser.add_argument("--participant", default="Datathon26")
    args = parser.parse_args()
    champion = json.loads(Path(args.champion).read_text())
    path = build(champion, Path(args.out), args.participant)
    print(f"Wrote {path} playing {champion['id']}.")


if __name__ == "__main__":
    main()
